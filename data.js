// 임의의 월/일(MM-DD)에 대해 해당 날짜의 실록·야사 목록을 반환하는 함수
function getStoriesForDate(month, day) {
  const key = `${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
  
  // 1. 정확히 큐레이션된 날짜 데이터가 있는 경우
  if (CURATED_STORIES[key] && CURATED_STORIES[key].length >= 4) {
    return CURATED_STORIES[key];
  }

  const existing = CURATED_STORIES[key] ? [...CURATED_STORIES[key]] : [];
  const usedIds = new Set(existing.map(s => s.id));

  // 2. 부족한 카테고리를 채워 모든 날짜(365일)에서 4대 테마 야사를 즐길 수 있도록 구성
  const daySeed = month * 31 + day;
  const seasonNames = {
    1: "맹동(孟冬)·소한 무렵", 2: "입춘(立春) 무렵", 3: "춘삼월(春三月)", 4: "청명·곡우 무렵",
    5: "신록의 오월", 6: "유월 하지 무렵", 7: "삼복더위 무렵", 8: "처서·추풍 무렵",
    9: "가을 국화철", 10: "상달(十月)", 11: "초겨울 동짓달 문턱", 12: "섣달 세모(歲暮)"
  };

  const neededCategories = ['mystery', 'scandal', 'folklore', 'episode'].filter(
    cat => !existing.some(s => s.category === cat)
  );

  neededCategories.forEach((cat, idx) => {
    const poolForCat = DAILY_ARCHIVE_POOL.filter(item => item.category === cat);
    const chosen = poolForCat[(daySeed + idx) % poolForCat.length];
    if (chosen) {
      const generatedId = `${String(month).padStart(2, '0')}${String(day).padStart(2, '0')}-${cat}`;
      if (!usedIds.has(generatedId)) {
        existing.push({
          ...chosen,
          id: generatedId,
          month,
          day,
          lunarDate: `${seasonNames[month]} (${month}월 ${day}일 매칭 기록)`
        });
      }
    }
  });

  // 흥미도(interestScore) 순으로 정렬
  return existing.sort((a, b) => b.interestScore - a.interestScore);
}

// 역대 레전드 야사 TOP 리스트 반환
function getAllLegendStories() {
  const all = [];
  Object.values(CURATED_STORIES).forEach(list => {
    list.forEach(item => all.push(item));
  });
  DAILY_ARCHIVE_POOL.forEach((item, i) => {
    all.push({
      ...item,
      id: `pool-${i}`,
      month: ((i * 2) % 12) + 1,
      day: ((i * 5) % 28) + 1,
      lunarDate: `실록·야사 특선 아카이브`
    });
  });
  return all.sort((a, b) => b.interestScore - a.interestScore);
}
